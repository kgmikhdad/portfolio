"""Transactional, idempotent application-schema deployment; no trading or data reset."""

import re
import time
from pathlib import Path
from typing import Any

from alembic import command
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.script import ScriptDirectory
from sqlalchemy import Engine, inspect, select, text
from sqlalchemy.orm import Session

from investment_engine.broker import initialize, reconcile
from investment_engine.hosted_database import verified_engine
from investment_engine.models import Account, Base, LedgerEntry

SCHEMA = "investment_engine"
SCHEMA_MARKER = "adaptive-investment-engine:paper:v1"
PROJECT_ROOT = Path(__file__).resolve().parents[2]


class HostedSetupError(RuntimeError):
    pass


def initialize_database(db: Engine, schema: str = SCHEMA) -> dict[str, Any]:
    if db.dialect.name != "postgresql":
        raise HostedSetupError("hosted_setup_requires_postgresql")
    if not re.fullmatch(r"investment_engine(?:_test_[0-9a-f]{32})?", schema):
        raise HostedSetupError("invalid_application_schema")
    quote = db.dialect.identifier_preparer.quote_identifier
    quoted_schema = quote(schema)
    expected_tables = set(Base.metadata.tables) | {"alembic_version"}
    configuration = Config(str(PROJECT_ROOT / "alembic.ini"))
    configuration.set_main_option("script_location", str(PROJECT_ROOT / "migrations"))
    revision = ScriptDirectory.from_config(configuration).get_current_head()
    original_schema = db.dialect.default_schema_name
    try:
        with db.begin() as connection:
            original_schema = db.dialect.default_schema_name
            # One transaction covers schema, migrations, permissions and opening deposit.
            connection.execute(text("SET LOCAL lock_timeout = '15s'"))
            connection.execute(text("SET LOCAL statement_timeout = '60s'"))
            connection.execute(text("SELECT pg_advisory_xact_lock(627490218523710)"))
            existing_schema = connection.execute(
                text(
                    "SELECT obj_description(oid, 'pg_namespace') FROM pg_namespace "
                    "WHERE nspname=:schema"
                ),
                {"schema": schema},
            ).first()
            if existing_schema is None:
                connection.execute(text(f"CREATE SCHEMA {quoted_schema}"))
                connection.execute(text(f"COMMENT ON SCHEMA {quoted_schema} IS '{SCHEMA_MARKER}'"))
            elif existing_schema[0] != SCHEMA_MARKER:
                raise HostedSetupError("existing_schema_not_owned_by_this_application")
            existing_tables = set(inspect(connection).get_table_names(schema=schema))
            if existing_tables - expected_tables:
                raise HostedSetupError("unexpected_tables_in_application_schema")
            if existing_tables and "alembic_version" not in existing_tables:
                raise HostedSetupError("unversioned_tables_require_review")
            connection.execute(text(f"SET LOCAL search_path TO {quoted_schema}"))
            # Alembic's documented schema-per-tenant approach; default metadata stays portable.
            db.dialect.default_schema_name = schema
            configuration.attributes["connection"] = connection
            configuration.attributes["schema"] = schema
            command.upgrade(configuration, "head")
            actual_tables = set(inspect(connection).get_table_names(schema=schema))
            if actual_tables != expected_tables:
                raise HostedSetupError("application_table_set_mismatch")
            current = MigrationContext.configure(
                connection,
                opts={
                    "version_table_schema": schema,
                },
            ).get_current_heads()
            if current != (revision,):
                raise HostedSetupError("migration_revision_mismatch")
            # Avoid the project's autogenerated Data API roles receiving access to app tables.
            roles = ["PUBLIC"]
            for role in ("anon", "authenticated"):
                if connection.execute(
                    text("SELECT 1 FROM pg_roles WHERE rolname=:role"), {"role": role}
                ).scalar():
                    roles.append(quote(role))
            for role in roles:
                connection.execute(text(f"REVOKE ALL ON SCHEMA {quoted_schema} FROM {role}"))
                connection.execute(
                    text(f"REVOKE ALL ON ALL TABLES IN SCHEMA {quoted_schema} FROM {role}")
                )
                connection.execute(
                    text(f"REVOKE ALL ON ALL SEQUENCES IN SCHEMA {quoted_schema} FROM {role}")
                )
            public_grants: int = connection.execute(
                text(
                    "SELECT count(*) FROM pg_namespace n, "
                    "LATERAL aclexplode(coalesce(n.nspacl,acldefault('n',n.nspowner))) a "
                    "WHERE n.nspname=:schema AND a.grantee=0"
                ),
                {"schema": schema},
            ).scalar_one()
            if public_grants:
                raise HostedSetupError("public_schema_permissions_not_revoked")
            for role in roles[1:]:
                if connection.execute(
                    text("SELECT has_schema_privilege(:role, :schema, 'USAGE')"),
                    {"role": role.strip('"'), "schema": schema},
                ).scalar_one():
                    raise HostedSetupError("data_api_role_still_has_schema_access")
            for table in sorted(actual_tables):
                connection.execute(
                    text(f"ALTER TABLE {quoted_schema}.{quote(table)} ENABLE ROW LEVEL SECURITY")
                )
            with Session(bind=connection, join_transaction_mode="create_savepoint") as session:
                with session.begin():
                    created = session.get(Account, "paper") is None
                    account = initialize(session, "paper", int(time.time()))
                    if account.initial_paise != 10000000 or account.currency != "INR":
                        raise HostedSetupError("existing_account_configuration_mismatch")
                    if not account.stopped:
                        raise HostedSetupError("existing_account_emergency_stop_not_active")
                    reconciliation = reconcile(session, "paper")
                    deposits = session.scalars(
                        select(LedgerEntry).where(
                            LedgerEntry.account_id == "paper", LedgerEntry.kind == "initial"
                        )
                    ).all()
                    if len(deposits) != 1 or deposits[0].amount_paise != 10000000:
                        raise HostedSetupError("initial_deposit_reconciliation_failed")
                    if created and reconciliation["cash_paise"] != 10000000:
                        raise HostedSetupError("new_account_cash_mismatch")
            secured: int = connection.execute(
                text(
                    "SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace "
                    "WHERE n.nspname=:schema AND c.relkind='r' AND c.relrowsecurity"
                ),
                {"schema": schema},
            ).scalar_one()
            if secured != len(expected_tables):
                raise HostedSetupError("row_security_verification_failed")
            result = {
                "status": "initialized",
                "schema": schema,
                "migration_revision": revision,
                "tables_verified": len(actual_tables),
                "account_created": created,
                "opening_deposit_verified": True,
                "ledger_reconciled": True,
                "emergency_stop_active": True,
                "row_security_enabled": True,
                "public_api_access_revoked": True,
                "existing_balances_preserved": True,
                "trades_executed": 0,
                "schedules_enabled": False,
            }
        # Check through a fresh connection after commit, so success means persisted state.
        with db.connect() as connection, connection.begin():
            connection.execute(text("SET TRANSACTION READ ONLY"))
            connection.execute(text(f"SET LOCAL search_path TO {quoted_schema}"))
            with Session(bind=connection, join_transaction_mode="create_savepoint") as session:
                reconcile(session, "paper")
                persisted = session.get(Account, "paper")
                if persisted is None or not persisted.stopped:
                    raise HostedSetupError("post_commit_verification_failed")
        result["post_commit_verified"] = True
        return result
    finally:
        db.dialect.default_schema_name = original_schema


def initialize_supabase(value: str) -> dict[str, Any]:
    db = verified_engine(value)
    try:
        return initialize_database(db)
    finally:
        db.dispose()
